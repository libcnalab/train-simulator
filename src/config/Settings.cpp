#include "trainsim/config/Settings.hpp"

#include "CnaEngine/Core/SettingsFile.hpp"

#include <algorithm>
#include <stdexcept>
#include <string>

namespace TrainSim::Config {

namespace {

// The file format is cna-engine's SettingsFile. What this game adds is strictness: a line that is
// not key=value, an unknown key or a value that is not a finite number is an error rather than a
// silent fallback, so a typo in a hand-edited file is reported instead of ignored.
constexpr std::string_view knownKeys[] = {
    "mouse_sensitivity", "master_volume", "announcement_volume", "passenger_volume",
    "train_volume", "camera_vibration", "field_of_view_degrees", "graphics_quality",
    "vegetation_distance_metres", "announcement_captions", "service_start_minutes", "weather"};

Settings read(const CnaEngine::SettingsFile& file, Settings settings)
{
    if (!file.Problems().empty())
        throw std::runtime_error("Expected key=value on settings line "
                                 + std::to_string(file.Problems().front().line));
    for (const auto& entry : file.Entries())
    {
        const std::string& key = entry.first;
        const std::string line = std::to_string(file.Line(key));
        if (std::find(std::begin(knownKeys), std::end(knownKeys), key) == std::end(knownKeys))
            throw std::runtime_error("Unknown setting '" + key + "' on line " + line);
        if (!file.TryGetFloat(key))
            throw std::runtime_error("Invalid numeric setting on line " + line);
    }

    settings.mouseSensitivity = file.GetFloat("mouse_sensitivity", settings.mouseSensitivity, 0.0005f, 0.010f);
    settings.masterVolume = file.GetFloat("master_volume", settings.masterVolume, 0.0f, 1.0f);
    settings.announcementVolume = file.GetFloat("announcement_volume", settings.announcementVolume, 0.0f, 1.0f);
    settings.passengerVolume = file.GetFloat("passenger_volume", settings.passengerVolume, 0.0f, 1.0f);
    settings.trainVolume = file.GetFloat("train_volume", settings.trainVolume, 0.0f, 1.0f);
    settings.cameraVibration = file.GetFloat("camera_vibration", settings.cameraVibration, 0.0f, 1.0f);
    settings.fieldOfViewDegrees = file.GetFloat("field_of_view_degrees", settings.fieldOfViewDegrees, 55.0f, 100.0f);
    settings.graphicsQuality = file.GetInt("graphics_quality", settings.graphicsQuality, 0, 2);
    settings.vegetationDistanceMetres =
        file.GetFloat("vegetation_distance_metres", settings.vegetationDistanceMetres, 250.0f, 1'000.0f);
    settings.announcementCaptions = file.GetBool("announcement_captions", settings.announcementCaptions);
    settings.serviceStartMinutes = file.GetInt("service_start_minutes", settings.serviceStartMinutes, 0, 1'439);
    settings.weatherMode = file.GetInt("weather", settings.weatherMode, 0, 5);
    return settings;
}

CnaEngine::SettingsFile write(const Settings& settings)
{
    CnaEngine::SettingsFile file;
    file.SetHeader("User preferences generated by Train Simulator.");
    file.SetFloat("mouse_sensitivity", settings.mouseSensitivity);
    file.SetFloat("master_volume", settings.masterVolume);
    file.SetFloat("announcement_volume", settings.announcementVolume);
    file.SetFloat("passenger_volume", settings.passengerVolume);
    file.SetFloat("train_volume", settings.trainVolume);
    file.SetFloat("camera_vibration", settings.cameraVibration);
    file.SetFloat("field_of_view_degrees", settings.fieldOfViewDegrees);
    file.SetInt("graphics_quality", settings.graphicsQuality);
    file.SetFloat("vegetation_distance_metres", settings.vegetationDistanceMetres);
    file.SetBool("announcement_captions", settings.announcementCaptions);
    file.SetInt("service_start_minutes", settings.serviceStartMinutes);
    file.SetInt("weather", settings.weatherMode);
    return file;
}

} // namespace

Settings Settings::parse(std::string_view text)
{
    return parse(text, Settings{});
}

Settings Settings::parse(std::string_view text, Settings settings)
{
    return read(CnaEngine::SettingsFile::Parse(text), settings);
}

Settings Settings::load(const std::filesystem::path& path)
{
    return load(path, Settings{});
}

Settings Settings::load(const std::filesystem::path& path, Settings base)
{
    const CnaEngine::SettingsFile file = CnaEngine::SettingsFile::Load(path);
    // A file that cannot be read (a problem on line 0) leaves the settings as a missing one does.
    if (!file.Problems().empty() && file.Problems().front().line == 0) return base;
    return read(file, base);
}

std::string Settings::serialize() const
{
    return write(*this).Serialize();
}

void Settings::save(const std::filesystem::path& path) const
{
    write(*this).Save(path);
}

Settings settingsForPersistence(Settings runtime, int loadedGraphicsQuality,
                                bool launchQualityOverride,
                                bool graphicsQualityAdjustedInMenu) noexcept
{
    if (launchQualityOverride && !graphicsQualityAdjustedInMenu)
        runtime.graphicsQuality = std::clamp(loadedGraphicsQuality,0,2);
    return runtime;
}

} // namespace TrainSim::Config
